"""
Build the Vigil learning site from Markdown sources.  Offline, no dependencies.

    python docs/build_site.py

Reads  docs/src/*.md   (front matter: title, summary, section, order)
Writes docs/index.html (home) and docs/pages/*.html, plus docs/assets/.
Open docs/index.html in a browser; every link is relative, so no server is needed.

Markdown extras
  {{include path/to/file.py#symbol}}   embed a function/class/constant straight from the code,
                                       so snippets can never drift from the source
  {{flow: A ~ sub | B | C}}            left-to-right flow diagram
  {{fan: In | A, B, C | Out}}          fan-out / fan-in diagram
  ??? Question                         collapsible answer; indent the answer by 4 spaces
  > **Tip** text                       callout (Tip, Note, Warning, Try it)
"""

from __future__ import annotations

import ast
import html
import json
import os
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
ROOT = DOCS.parent
SRC = DOCS / "src"
SECTIONS = ["Start here", "Levels", "Practice", "Reference"]

sys.path.insert(0, str(DOCS))


# ─── Markdown ─────────────────────────────────────────────────────────────────

def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", text).lower()).strip("-")


class Ctx:
    """Per-page state shared by the inline renderer."""

    def __init__(self, name: str, pages: dict[str, dict]):
        self.name, self.pages = name, pages
        self.toc: list[tuple[int, str, str]] = []

    def href(self, target: str) -> str:
        if target in ("", "#") or re.match(r"^(https?:|mailto:|#)", target):
            return target
        path, _, frag = target.partition("#")
        if path.endswith(".md") and path[:-3] in self.pages:
            dest = out_path(path[:-3])
            rel = os.path.relpath(dest, out_path(self.name).parent).replace("\\", "/")
            return rel + (f"#{frag}" if frag else "")
        if path == "reference.md":  # generated by build_docs.py
            rel = os.path.relpath(DOCS / "pages" / "reference.html", out_path(self.name).parent)
            return rel.replace("\\", "/") + (f"#{frag}" if frag else "")
        if path.startswith("repo:"):  # link to a file in the repository
            rel = os.path.relpath(ROOT / path[5:], out_path(self.name).parent).replace("\\", "/")
            return rel
        return target


def out_path(name: str) -> Path:
    return DOCS / "index.html" if name == "index" else DOCS / "pages" / f"{name}.html"


def inline(text: str, ctx: Ctx) -> str:
    codes: list[str] = []

    def stash(m):
        codes.append(f"<code>{html.escape(m.group(1))}</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", stash, text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)",
                  lambda m: f'<a href="{html.escape(ctx.href(m.group(2)))}">{m.group(1)}</a>', text)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


_PY_TOKEN = re.compile(
    r'(?P<c>#[^\n]*)|(?P<s>"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'|f?"(?:\\.|[^"\\\n])*"|f?\'(?:\\.|[^\'\\\n])*\')'
    r"|(?P<k>\b(?:def|class|return|if|elif|else|for|while|in|not|and|or|is|import|from|as|with|try|except|finally|"
    r"raise|await|async|lambda|None|True|False|yield|pass|global|assert)\b)|(?P<n>\b\d[\d_.]*\b)"
)
_SH_TOKEN = re.compile(r"(?P<c>(?:^|\s)#[^\n]*)|(?P<s>\"[^\"\n]*\"|'[^'\n]*')")


def highlight(code: str, lang: str) -> str:
    pat = _PY_TOKEN if lang == "python" else _SH_TOKEN if lang in ("bash", "sh", "powershell") else None
    if pat is None:
        return html.escape(code)
    out, pos = [], 0
    for m in pat.finditer(code):
        out.append(html.escape(code[pos:m.start()]))
        kind = m.lastgroup
        out.append(f'<span class="t-{kind}">{html.escape(m.group())}</span>')
        pos = m.end()
    out.append(html.escape(code[pos:]))
    return "".join(out)


def code_block(code: str, lang: str, caption: str = "") -> str:
    cap = f'<div class="code-cap">{html.escape(caption)}</div>' if caption else ""
    return (f'<div class="code">{cap}<button class="copy" type="button" aria-label="Copy code">Copy</button>'
            f'<pre><code>{highlight(code.rstrip(), lang)}</code></pre></div>')


def include(spec: str) -> str:
    """{{include path#symbol}} -> source of a top-level def/class/assignment, taken from the real file."""
    path, _, symbol = spec.partition("#")
    file = ROOT / path
    src = file.read_text(encoding="utf-8")
    tree = ast.parse(src)
    for node in tree.body:
        names = []
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names = [node.name]
        elif isinstance(node, ast.Assign):
            names = [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names = [node.target.id]
        if symbol in names:
            start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
            seg = "\n".join(src.splitlines()[start - 1: node.end_lineno])
            return code_block(seg, "python", f"{path} · {symbol}")
    raise SystemExit(f"include: symbol '{symbol}' not found in {path}")


def directive(line: str, ctx: Ctx) -> str | None:
    m = re.match(r"^\{\{(\w+):?\s*(.*?)\}\}$", line.strip())
    if not m:
        return None
    kind, arg = m.groups()
    if kind == "include":
        return include(arg)
    if kind == "flow":
        nodes = []
        for part in arg.split("|"):
            title, _, sub = part.partition("~")
            nodes.append(f'<div class="node"><b>{inline(title.strip(), ctx)}</b>'
                         + (f"<small>{inline(sub.strip(), ctx)}</small>" if sub.strip() else "") + "</div>")
        return '<div class="flow" role="img">' + '<span class="arr">→</span>'.join(nodes) + "</div>"
    if kind == "fan":
        src, mid, dst = [p.strip() for p in arg.split("|")]
        items = "".join(f'<div class="node">{inline(x.strip(), ctx)}</div>' for x in mid.split(","))
        return ('<div class="fan" role="img">'
                f'<div class="node">{inline(src, ctx)}</div><span class="arr">→</span>'
                f'<div class="lane">{items}</div><span class="arr">→</span>'
                f'<div class="node">{inline(dst, ctx)}</div></div>')
    raise SystemExit(f"unknown directive {kind}")


def render(md: str, ctx: Ctx) -> str:
    lines = md.splitlines()
    out: list[str] = []
    i = 0

    def para_break(s: str) -> bool:
        return (not s.strip() or re.match(r"^(#{1,4} |```|> |- |\d+\. |\||\?\?\? |\{\{|<)", s) is not None)

    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
        elif ln.startswith("```"):
            lang, buf = ln[3:].strip(), []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1
            out.append(code_block("\n".join(buf), lang))
        elif ln.startswith("{{"):
            d = directive(ln, ctx)
            if d is None:
                raise SystemExit(f"bad directive: {ln}")
            out.append(d)
            i += 1
        elif ln.startswith("<"):  # raw html until blank line
            buf = []
            while i < len(lines) and lines[i].strip():
                buf.append(lines[i])
                i += 1
            out.append("\n".join(buf))
        elif re.match(r"^#{1,4} ", ln):
            level = len(ln) - len(ln.lstrip("#"))
            text = ln[level:].strip()
            sid = slug(text)
            if level in (2, 3):
                ctx.toc.append((level, text.replace("`", ""), sid))
            out.append(f'<h{level} id="{sid}">{inline(text, ctx)}</h{level}>')
            i += 1
        elif re.match(r"^---+$", ln.strip()):
            out.append("<hr>")
            i += 1
        elif ln.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s:|-]+\|?$", lines[i + 1]):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, body = rows[0], rows[2:]
            t = "<div class='table'><table><thead><tr>" + "".join(f"<th>{inline(c, ctx)}</th>" for c in head)
            t += "</tr></thead><tbody>"
            for r in body:
                t += "<tr>" + "".join(f"<td>{inline(c, ctx)}</td>" for c in r) + "</tr>"
            out.append(t + "</tbody></table></div>")
        elif ln.startswith("> "):
            buf = []
            while i < len(lines) and lines[i].startswith(">"):
                buf.append(lines[i][1:].strip())
                i += 1
            text = " ".join(buf)
            m = re.match(r"\*\*(Tip|Note|Warning|Try it)\*\*:?\s*(.*)", text)
            kind, body = (m.group(1), m.group(2)) if m else ("Note", text)
            out.append(f'<aside class="callout {slug(kind)}"><strong>{kind}</strong><p>{inline(body, ctx)}</p></aside>')
        elif ln.startswith("??? "):
            q, buf = ln[4:].strip(), []
            i += 1
            while i < len(lines) and (lines[i].startswith("    ") or not lines[i].strip()):
                buf.append(lines[i][4:])
                i += 1
            out.append(f"<details><summary>{inline(q, ctx)}</summary>{render(chr(10).join(buf), ctx)}</details>")
        elif re.match(r"^(- |\d+\. )", ln):
            ordered = ln[0].isdigit()
            items: list[str] = []
            while i < len(lines) and re.match(r"^(- |\d+\. )", lines[i]):
                item = re.sub(r"^(- |\d+\. )", "", lines[i])
                i += 1
                while i < len(lines) and lines[i].startswith("  ") and lines[i].strip():
                    item += " " + lines[i].strip()
                    i += 1
                items.append(item)
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(x, ctx)}</li>" for x in items) + f"</{tag}>")
        else:
            buf = [ln]
            i += 1
            while i < len(lines) and not para_break(lines[i]):
                buf.append(lines[i])
                i += 1
            out.append(f"<p>{inline(' '.join(s.strip() for s in buf), ctx)}</p>")
    return "\n".join(out)


# ─── Pages ────────────────────────────────────────────────────────────────────

def load_pages() -> dict[str, dict]:
    pages = {}
    for f in sorted(SRC.glob("*.md")):
        text = f.read_text(encoding="utf-8").replace("\r\n", "\n")
        m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
        if not m:
            raise SystemExit(f"{f.name}: missing front matter")
        meta = {k: v.strip().strip('"') for k, v in re.findall(r"^(\w+):\s*(.*)$", m.group(1), re.MULTILINE)}
        pages[f.stem] = {"meta": meta, "body": m.group(2), "name": f.stem}
    return pages


def ordered(pages: dict[str, dict]) -> list[dict]:
    key = lambda p: (SECTIONS.index(p["meta"]["section"]), int(p["meta"].get("order", 99)))
    return sorted(pages.values(), key=key)


def page_html(page: dict, pages: dict[str, dict], seq: list[dict], body_html: str, toc) -> str:
    here = out_path(page["name"])
    base = os.path.relpath(DOCS, here.parent).replace("\\", "/")
    base = "" if base == "." else base + "/"
    rel = lambda name: os.path.relpath(out_path(name), here.parent).replace("\\", "/")

    nav = ""
    for sec in SECTIONS:
        items = [p for p in seq if p["meta"]["section"] == sec]
        links = "".join(
            f'<a href="{rel(p["name"])}"{" aria-current=page" if p["name"] == page["name"] else ""}>'
            f'{html.escape(p["meta"]["title"])}</a>' for p in items)
        if sec == "Reference":
            links += f'<a href="{os.path.relpath(DOCS / "pages" / "reference.html", here.parent).replace(chr(92), "/")}">Code reference</a>'
        nav += f'<div class="nav-sec"><h4>{sec}</h4>{links}</div>'

    idx = seq.index(page)
    prev_ = seq[idx - 1] if idx > 0 else None
    next_ = seq[idx + 1] if idx + 1 < len(seq) else None
    pn = '<nav class="prevnext" aria-label="Previous and next page">'
    pn += (f'<a class="prev" href="{rel(prev_["name"])}"><small>Previous</small>{html.escape(prev_["meta"]["title"])}</a>'
           if prev_ else "<span></span>")
    pn += (f'<a class="next" href="{rel(next_["name"])}"><small>Next</small>{html.escape(next_["meta"]["title"])}</a>'
           if next_ else "<span></span>")
    pn += "</nav>"

    toc_html = ""
    if len(toc) > 1:
        toc_html = ('<aside class="toc"><h4>On this page</h4>' +
                    "".join(f'<a class="l{lv}" href="#{sid}">{html.escape(t)}</a>' for lv, t, sid in toc) + "</aside>")

    title = html.escape(page["meta"]["title"])
    summary = html.escape(page["meta"].get("summary", ""))
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · Vigil Guide</title>
<meta name="description" content="{summary}">
<link rel="stylesheet" href="{base}assets/style.css">
<script>try{{var t=localStorage.getItem('vigil-theme');if(t)document.documentElement.dataset.theme=t}}catch(e){{}}</script>
</head>
<body data-base="{base}">
<a class="skip" href="#content">Skip to content</a>
<header class="top">
  <button id="menu" type="button" aria-label="Open menu">☰</button>
  <a class="brand" href="{base}index.html"><span>🛡️</span> Vigil Guide</a>
  <div class="search"><input id="q" type="search" placeholder="Search the guide…" autocomplete="off" aria-label="Search"><div id="results" hidden></div></div>
  <button id="theme" type="button" aria-label="Toggle dark mode">◐</button>
</header>
<div class="layout">
  <nav class="side" id="side" aria-label="Guide">{nav}</nav>
  <main id="content">
    <article>
      <p class="eyebrow">{html.escape(page["meta"]["section"])}</p>
      {body_html}
    </article>
    {pn}
  </main>
  {toc_html}
</div>
<script src="{base}assets/search-index.js"></script>
<script src="{base}assets/app.js"></script>
</body>
</html>
"""


def strip_md(md: str) -> str:
    md = re.sub(r"```[\s\S]*?```", " ", md)
    md = re.sub(r"\{\{[^}]*\}\}", " ", md)
    md = re.sub(r"[`*#>|\[\]]|\(\S+?\)", " ", md)
    return re.sub(r"\s+", " ", md).strip()


def build() -> None:
    import build_docs

    pages = load_pages()
    seq = ordered(pages)
    (DOCS / "pages").mkdir(exist_ok=True)
    index = []
    for page in seq:
        ctx = Ctx(page["name"], pages)
        body = render(page["body"], ctx)
        dest = out_path(page["name"])
        dest.write_text(page_html(page, pages, seq, body, ctx.toc), encoding="utf-8")
        rel = dest.relative_to(DOCS).as_posix()
        index.append({"t": page["meta"]["title"], "u": rel, "s": page["meta"].get("summary", ""),
                      "h": [t for _, t, _ in ctx.toc], "x": strip_md(page["body"])})
    (DOCS / "assets").mkdir(exist_ok=True)
    (DOCS / "assets" / "search-index.js").write_text(
        "window.VIGIL_INDEX=" + json.dumps(index, ensure_ascii=False) + ";", encoding="utf-8")
    ref = build_docs.build()
    print(f"built {len(seq)} guide pages + {ref.relative_to(DOCS)}")


if __name__ == "__main__":
    build()
